  function lookup(s) {
    if (!s) return null;
    if (Object.prototype.hasOwnProperty.call(EN, s)) return EN[s];
    for (const [re, rep] of EN_RE) {
      if (re.test(s)) return s.replace(re, rep);
    }
    for (const sep of [' · ', ' – ']) {
      if (!s.includes(sep)) continue;
      let any = false;
      const parts = s.split(sep).map((p) => {
        const t = lookup(p.trim());
        if (t === null) return p;
        any = true;
        return t;
      });
      if (any) return parts.join(sep);
    }
    return null;
  }

